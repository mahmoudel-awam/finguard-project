-- -------------------------------------------------------------
-- TABLE 5: daily_summary
-- Aggregated daily report generated by Airflow every midnight.
-- Powers dashboards and management reporting.
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS daily_summary (
    summary_id          SERIAL          PRIMARY KEY,
    report_date         DATE            NOT NULL UNIQUE,
    total_transactions  INTEGER         DEFAULT 0,
    total_volume_egp    NUMERIC(20, 2)  DEFAULT 0,
    fraud_count         INTEGER         DEFAULT 0,
    laundering_count    INTEGER         DEFAULT 0,
    suspicious_count    INTEGER         DEFAULT 0,
    high_risk_count     INTEGER         DEFAULT 0,
    normal_count        INTEGER         DEFAULT 0,
    fraud_rate_pct      NUMERIC(5, 2)   GENERATED ALWAYS AS (
                            CASE
                                WHEN total_transactions = 0 THEN 0
                                ELSE ROUND((fraud_count * 100.0) / total_transactions, 2)
                            END
                        ) STORED,
    generated_at        TIMESTAMP       DEFAULT CURRENT_TIMESTAMP
);

-- =============================================================
-- INDEXES — for query performance on large transaction volumes
-- =============================================================
CREATE INDEX IF NOT EXISTS idx_transactions_type
    ON transactions(transaction_type);

CREATE INDEX IF NOT EXISTS idx_transactions_ts
    ON transactions(ts);

CREATE INDEX IF NOT EXISTS idx_fraud_alerts_type
    ON fraud_alerts(alert_type);

CREATE INDEX IF NOT EXISTS idx_fraud_alerts_detected
    ON fraud_alerts(detected_at);

CREATE INDEX IF NOT EXISTS idx_audit_log_component
    ON audit_log(component, created_at);
