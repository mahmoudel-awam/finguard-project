-- =============================================================
-- FinGuard PostgreSQL Schema
-- Real-Time Financial Fraud Detection Pipeline
-- =============================================================

-- -------------------------------------------------------------
-- TABLE 1: transactions
-- The raw ledger. Every transaction ingested from Kafka lands here.
-- Source: consumers/consumer.py via KafkaConsumer
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS transactions (
    transaction_id      VARCHAR(50)     PRIMARY KEY,
    ts                  TIMESTAMP       NOT NULL,
    sender_account      VARCHAR(20)     NOT NULL,
    receiver_account    VARCHAR(20)     NOT NULL,
    amount              NUMERIC(15, 2)  NOT NULL,
    currency            VARCHAR(10)     DEFAULT 'EGP',
    sender_bank         VARCHAR(50),
    receiver_bank       VARCHAR(50),
    sender_country      VARCHAR(50)     DEFAULT 'Egypt',
    receiver_country    VARCHAR(50),
    transaction_type    VARCHAR(30),
    status              VARCHAR(20)     DEFAULT 'PROCESSED',
    ingested_at         TIMESTAMP       DEFAULT CURRENT_TIMESTAMP
);

-- -------------------------------------------------------------
-- TABLE 2: fraud_alerts
-- Only flagged transactions. Written when alert != 'NORMAL'.
-- Source: consumers/consumer.py — second INSERT block
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS fraud_alerts (
    alert_id            SERIAL          PRIMARY KEY,
    transaction_id      VARCHAR(50)     NOT NULL REFERENCES transactions(transaction_id),
    alert_type          VARCHAR(30)     NOT NULL,
    amount              NUMERIC(15, 2)  NOT NULL,
    sender_account      VARCHAR(20),
    receiver_account    VARCHAR(20),
    sender_bank         VARCHAR(50),
    receiver_country    VARCHAR(50),
    risk_level          VARCHAR(10)     GENERATED ALWAYS AS (
                            CASE
                                WHEN alert_type = 'MONEY LAUNDERING'  THEN 'CRITICAL'
                                WHEN alert_type = 'FRAUD DETECTED'    THEN 'HIGH'
                                WHEN alert_type = 'HIGH RISK COUNTRY' THEN 'HIGH'
                                WHEN alert_type = 'SUSPICIOUS'        THEN 'MEDIUM'
                                ELSE 'LOW'
                            END
                        ) STORED,
    detected_at         TIMESTAMP       DEFAULT CURRENT_TIMESTAMP
);

-- -------------------------------------------------------------
-- TABLE 3: audit_log
-- Immutable record of every pipeline action for compliance.
-- Every INSERT, every Airflow task run, every schema change.
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS audit_log (
    log_id              SERIAL          PRIMARY KEY,
    event_type          VARCHAR(50)     NOT NULL,
    component           VARCHAR(50),
    transaction_id      VARCHAR(50),
    description         TEXT,
    status              VARCHAR(20)     DEFAULT 'SUCCESS',
    created_at          TIMESTAMP       DEFAULT CURRENT_TIMESTAMP
);

